#!/usr/bin/env python3
"""Packs cyd/art/<state>_<n>.png into src/capy_frames.h.

Any 64x48 PNG works (RGB, RGBA or indexed). Transparent pixels are alpha < 128
or pure magenta (255,0,255). Colours are snapped to the nearest entry of the
16-colour palette below, so a Blender render will come out posterised; for best
results paint with these colours (or edit PAL here and in make_capy.py).

Usage: python3 tools/frames2header.py
"""
import os, glob, re, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, "..", "art")
OUT = os.path.join(HERE, "..", "src", "capy_frames.h")
W, H = 64, 48
STATES = ["idle", "sniff", "safe", "stop", "sleep"]

PAL = [
    (255, 0, 255), (46, 26, 16), (156, 100, 54), (190, 134, 80), (118, 72, 38),
    (222, 186, 136), (22, 18, 18), (255, 255, 255), (246, 142, 32), (204, 104, 22),
    (76, 156, 62), (232, 148, 148), (226, 52, 44), (124, 184, 240), (250, 222, 84),
    (96, 96, 96),
]


def rgb565(c):
    r, g, b = c
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def nearest(c):
    best, bd = 1, 1 << 30
    for i, p in enumerate(PAL):
        if i == 0:
            continue
        d = sum((a - b) ** 2 for a, b in zip(c, p))
        if d < bd:
            best, bd = i, d
    return best


def load(path):
    im = Image.open(path).convert("RGBA")
    if im.size != (W, H):
        sys.exit(f"{path}: expected {W}x{H}, got {im.size}")
    px = im.load()
    data = bytearray(W * H)
    for y in range(H):
        for x in range(W):
            r, g, b, a = px[x, y]
            if a < 128 or (r, g, b) == (255, 0, 255):
                data[y * W + x] = 0
            else:
                data[y * W + x] = nearest((r, g, b))
    return bytes(data)


def main():
    frames = {}
    for st in STATES:
        files = sorted(glob.glob(os.path.join(ART, f"{st}_*.png")),
                       key=lambda p: int(re.search(r"_(\d+)\.png$", p).group(1)))
        if not files:
            sys.exit(f"no frames for state '{st}' in {ART}")
        frames[st] = [load(f) for f in files]

    with open(OUT, "w") as f:
        f.write("// Generated by tools/frames2header.py from cyd/art/*.png. Do not edit by hand.\n")
        f.write("#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n")
        f.write(f"#define CAPY_W {W}\n#define CAPY_H {H}\n#define CAPY_COLORS {len(PAL)}\n\n")
        f.write("static const uint16_t CAPY_PALETTE[CAPY_COLORS] PROGMEM = {\n    ")
        f.write(", ".join(f"0x{rgb565(c):04X}" for c in PAL))
        f.write("\n};\n\n")
        for st, fr in frames.items():
            for i, data in enumerate(fr):
                f.write(f"static const uint8_t CAPY_{st.upper()}_{i}[CAPY_W * CAPY_H] PROGMEM = {{\n")
                for y in range(H):
                    row = data[y * W:(y + 1) * W]
                    f.write("    " + ",".join(str(v) for v in row) + ",\n")
                f.write("};\n")
            f.write(f"static const uint8_t* const CAPY_{st.upper()}[] PROGMEM = {{ ")
            f.write(", ".join(f"CAPY_{st.upper()}_{i}" for i in range(len(fr))))
            f.write(" };\n")
            f.write(f"#define CAPY_{st.upper()}_N {len(fr)}\n\n")
    total = sum(len(v) for v in frames.values())
    print(f"wrote {OUT} ({total} frames, {total * W * H} bytes)")


if __name__ == "__main__":
    main()
